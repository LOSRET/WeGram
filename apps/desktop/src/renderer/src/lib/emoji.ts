/**
 * Search-tab match: the name, its synonyms and the glyph itself. Empty input
 * matches nothing (the tab shows the hint instead).
 */
export function searchEmoji(query: string): EmojiItem[] {
  const needle = normalizeQuery(query)
  if (!needle) return []
  return EMOJI.filter((item) =>
    containsText(`${item.name} ${item.keywords ?? ''} ${item.char}`, needle),
  )
}

/**
 * Moves a picked emoji to the front of the recent row, dropping the older copy
 * so a repeatedly used face stays one cell wide.
 */
export function mergeRecentEmoji(previous: readonly string[], picked: string): string[] {
  const kept = previous.filter((item) => item.length > 0 && item !== picked)
  if (!picked) return kept.slice(0, RECENT_EMOJI_LIMIT)
  return [picked, ...kept].slice(0, RECENT_EMOJI_LIMIT)
}
